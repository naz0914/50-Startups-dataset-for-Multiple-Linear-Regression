// Update Calculation logic
function updateCalculation() {
  const lstat = parseFloat(document.getElementById('slider-lstat').value);
  const ptratio = parseFloat(document.getElementById('slider-ptratio').value);
  const rad = parseFloat(document.getElementById('slider-rad').value);
  const tax = parseFloat(document.getElementById('slider-tax').value);
  const rm = parseFloat(document.getElementById('slider-rm').value);
  const dis = parseFloat(document.getElementById('slider-dis').value);
  const crim = parseFloat(document.getElementById('slider-crim').value);

  // Update slider displays
  document.getElementById('val-lstat').textContent = lstat.toFixed(1) + '%';
  document.getElementById('val-ptratio').textContent = ptratio.toFixed(1);
  document.getElementById('val-rad').textContent = Math.round(rad);
  document.getElementById('val-tax').textContent = '$' + Math.round(tax);
  document.getElementById('val-rm').textContent = rm.toFixed(1) + ' 間';
  document.getElementById('val-dis').textContent = dis.toFixed(1) + ' km';
  document.getElementById('val-crim').textContent = crim.toFixed(2);

  let pred_k = 0; // in thousands ($1k)
  let formulaStr = '';
  let ciMargin = 0;

  if (currentMode === 'top4') {
    const b0 = APP_DATA.top_model.intercept;
    const w_lstat = APP_DATA.top_model.coefs['LSTAT'];
    const w_ptratio = APP_DATA.top_model.coefs['PTRATIO'];
    const w_rad = APP_DATA.top_model.coefs['RAD'];
    const w_tax = APP_DATA.top_model.coefs['TAX'];

    pred_k = b0 + (w_lstat * lstat) + (w_ptratio * ptratio) + (w_rad * rad) + (w_tax * tax);
    ciMargin = 1.96 * (APP_DATA.top_model.rmse / Math.sqrt(30)); // 30 test samples
    formulaStr = 'ŷ = ' + fmtNum(b0, 2) + 
      ' + (' + fmtNum(w_lstat, 4) + ' × ' + lstat.toFixed(1) + ')' +
      ' + (' + fmtNum(w_ptratio, 4) + ' × ' + ptratio.toFixed(1) + ')' +
      ' + (' + fmtNum(w_rad, 4) + ' × ' + rad + ')' +
      ' + (' + fmtNum(w_tax, 4) + ' × ' + tax + ')';
  } else {
    const b0 = APP_DATA.full_model.intercept;
    const c = APP_DATA.full_model.coefs;

    pred_k = b0 + 
      (c['CRIM'] * crim) +
      (c['ZN'] * BASELINE_MEDIANS['ZN']) +
      (c['INDUS'] * BASELINE_MEDIANS['INDUS']) +
      (c['CHAS'] * currentChas) +
      (c['NOX'] * BASELINE_MEDIANS['NOX']) +
      (c['RM'] * rm) +
      (c['AGE'] * BASELINE_MEDIANS['AGE']) +
      (c['DIS'] * dis) +
      (c['RAD'] * rad) +
      (c['TAX'] * tax) +
      (c['PTRATIO'] * ptratio) +
      (c['B'] * BASELINE_MEDIANS['B']) +
      (c['LSTAT'] * lstat);

    ciMargin = 1.96 * (APP_DATA.full_model.rmse / Math.sqrt(30));
    formulaStr = 'ŷ = ' + fmtNum(b0, 2) + 
      ' + (' + fmtNum(c['RM'], 3) + ' × ' + rm.toFixed(1) + ')' +
      ' + (' + fmtNum(c['LSTAT'], 3) + ' × ' + lstat.toFixed(1) + ')' +
      ' + (' + fmtNum(c['PTRATIO'], 3) + ' × ' + ptratio.toFixed(1) + ')' +
      ' + (' + fmtNum(c['CHAS'], 3) + ' × ' + currentChas + ') + ... (13 項)';
  }

  if (pred_k < 5.0) pred_k = 5.0; // Floor at minimum baseline

  const predDollars = pred_k * 1000;
  const ciLowDollars = (pred_k - ciMargin) * 1000;
  const ciHighDollars = (pred_k + ciMargin) * 1000;
  const marginDollars = ciMargin * 1000;

  document.getElementById('pred-price').textContent = fmtCurr(predDollars);
  document.getElementById('pred-ci').textContent = 
    '95% 預測信賴區間: ' + fmtCurr(ciLowDollars) + ' ~ ' + fmtCurr(ciHighDollars) + ' (±' + fmtCurr(marginDollars) + ')';
  document.getElementById('pred-formula').textContent = formulaStr;
}

