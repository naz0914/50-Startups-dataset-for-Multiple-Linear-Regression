// Initialize Coefficients & VIF Table
function initCoefficientsTable() {
  const tbody = document.getElementById('coef-table-body');
  tbody.innerHTML = '';

  APP_DATA.full_model.coef_table.forEach(row => {
    const tr = document.createElement('tr');

    let stars = '';
    if (row.p < 0.001) stars = '<span style="color:#10b981; font-weight:700;">***</span>';
    else if (row.p < 0.01) stars = '<span style="color:#10b981; font-weight:700;">**</span>';
    else if (row.p < 0.05) stars = '<span style="color:#059669; font-weight:700;">*</span>';
    else stars = '<span style="color:#94a3b8;">ns</span>';

    let vifCell = '-';
    if (row.vif !== null && row.vif !== undefined) {
      const isWarn = row.vif > 5.0;
      vifCell = `<span class="${isWarn ? 'badge-warning' : 'badge-good'}">${fmtNum(row.vif, 2)}</span>`;
    }

    tr.innerHTML = `
      <td><strong>${row.feature}</strong></td>
      <td style="font-family: var(--font-mono); font-weight: 600;">${fmtNum(row.coef, 4)}</td>
      <td style="font-family: var(--font-mono);">${fmtNum(row.se, 4)}</td>
      <td style="font-family: var(--font-mono);">${fmtNum(row.t, 3)}</td>
      <td style="font-family: var(--font-mono);">${row.p < 0.0001 ? '< 0.0001' : fmtNum(row.p, 4)}</td>
      <td style="font-family: var(--font-mono); font-size: 0.8rem;">[${fmtNum(row.ci_low, 3)}, ${fmtNum(row.ci_high, 3)}]</td>
      <td>${vifCell}</td>
      <td>${stars}</td>
    `;
    tbody.appendChild(tr);
  });
}

